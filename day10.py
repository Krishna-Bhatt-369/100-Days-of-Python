#Functions


def hello():
    print("Hello, Python")


hello()

def welcome():
    print("Welcome to Python class")

welcome()

def greet(name):
    print("Hello, " + name)


greet("Ram")
greet("Sita")


def student(name, age):
    print("Student name:", name)
    print("Student age:", age)

student("Ram", 20)
student("Geeta", 22)


